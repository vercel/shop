import sanitizeHtml from "sanitize-html";

// Everything listed renders without running code or submitting data; unlisted markup such as srcdoc, formaction, and custom elements can.
const SHOPIFY_HTML_OPTIONS: sanitizeHtml.IOptions = {
  allowedAttributes: {
    "*": [
      "align",
      "allow",
      "allowfullscreen",
      "alt",
      "aria-*",
      "autoplay",
      "bgcolor",
      "border",
      "cellpadding",
      "cellspacing",
      "cite",
      "class",
      "color",
      "colspan",
      "controls",
      "crossorigin",
      "datetime",
      "decoding",
      "default",
      "dir",
      "download",
      "face",
      "frameborder",
      "headers",
      "height",
      "hidden",
      "href",
      "hreflang",
      "id",
      "kind",
      "label",
      "lang",
      "loading",
      "loop",
      "media",
      "muted",
      "open",
      "playsinline",
      "poster",
      "preload",
      "referrerpolicy",
      "rel",
      "reversed",
      "role",
      "rowspan",
      "sandbox",
      "scope",
      "size",
      "sizes",
      "span",
      "src",
      "srclang",
      "srcset",
      "start",
      "style",
      "target",
      "title",
      "type",
      "valign",
      "value",
      "width",
    ],
    a: ["name"],
  },
  allowedSchemes: ["http", "https", "mailto", "tel"],
  allowedSchemesByTag: { iframe: ["https"], img: ["data", "http", "https"] },
  allowedTags: [
    ...sanitizeHtml.defaults.allowedTags,
    "audio",
    "big",
    "center",
    "del",
    "details",
    "font",
    "iframe",
    "img",
    "ins",
    "picture",
    "source",
    "strike",
    "summary",
    "track",
    "tt",
    "video",
  ],
  allowIframeRelativeUrls: false,
  // An iframe loses its src unless it is an https URL; drop it rather than render an empty frame.
  exclusiveFilter: (frame) => frame.tag === "iframe" && !frame.attribs.src,
  // sanitize-html drops the attributes on this list when empty, and an empty sandbox is the strictest one.
  nonBooleanAttributes: sanitizeHtml.defaults.nonBooleanAttributes.filter(
    (name) => !["crossorigin", "download", "hidden", "sandbox"].includes(name),
  ),
  selfClosing: [...sanitizeHtml.defaults.selfClosing, "source", "track"],
  transformTags: {
    a: (tagName, attribs) => ({
      attribs: attribs.target === "_blank" ? { ...attribs, rel: "noopener noreferrer" } : attribs,
      tagName,
    }),
  },
};

// Shopify returns rich text exactly as staff and apps wrote it, scripts and event handlers included.
export function sanitizeShopifyHtml(html: string): string {
  return sanitizeHtml(html, SHOPIFY_HTML_OPTIONS);
}
